//assignment operator

#include <stdio.h>
int main() {
    int age = 20;
    // age = age + 5;
    age += 5; //addition assignment operator
    age -= 5; //subtraction assignment operator
    age *= 5; //multiplication assignement operator
    age /= 5; //division assignment opeartor
    printf("my age is : %d",age);
    return 0;
}


